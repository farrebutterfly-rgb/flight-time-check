"""Write SEARCHES.md: every search with its class and both screenshots.

    python3 gallery.py
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
LABEL = {"shifted": "Wrong hour", "utc_label": "Right digits, shown as UTC", "rescued": "Right, model corrected it",
         "ok": "Right, unaffected", "void": "No nonstop flights"}


def build():
    results = json.load(open(HERE / "data" / "results.json", encoding="utf-8"))
    lines = ["# The searches", "",
             "Every search from 17 November 2026: what the website showed, what ChatGPT showed, and both screens.",
             "Generated by `gallery.py` from `data/results.json`.", ""]
    for r in results:
        n = r["n"]
        lines += [f"## {n}. {r['frm']} to {r['to']}: {LABEL[r['cls']]}", ""]
        first = next((row for row in r.get("rows", []) if row["web"]), None)
        if first:
            lines += ["| | Departs | Arrives |", "|---|---|---|",
                      f"| Website, {first['fn']} | {first['web'][0]} | {first['web'][1].replace('+1', ' next day')} |",
                      f"| ChatGPT | {first['dep']} | {first['arr'].replace('+1', ' next day')} |", ""]
        if r.get("note"):
            lines += [f"ChatGPT's own note: \"{r['note'].replace('VOID: ', '')}\"", ""]
        shots = [(k, HERE / "screenshots" / "searches" / f"r{n:02d}_{k}.jpg") for k in ("chat", "web")]
        shots = [(k, p) for k, p in shots if p.exists()]
        if shots:
            lines += ["| " + " | ".join("ChatGPT" if k == "chat" else "se.flightnetwork.com" for k, _ in shots) + " |",
                      "|" + "---|" * len(shots),
                      "| " + " | ".join(f"![Search {n}, {k}](screenshots/searches/{p.name})" for k, p in shots) + " |", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    (HERE / "SEARCHES.md").write_text(build(), encoding="utf-8")
    print("SEARCHES.md written")
